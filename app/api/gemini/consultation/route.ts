import { GoogleGenAI } from '@google/genai';
import { NextRequest, NextResponse } from 'next/server';

export async function POST(req: NextRequest) {
  try {
    const { message, city, pestIssue, history } = await req.json();

    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      // Return a professional fallback answer if no key is supplied
      return NextResponse.json({
        reply: `أهلاً بك في حصن المملكة لمكافحة الحشرات والتعقيم. بخصوص استفسارك عن (${pestIssue || 'مكافحة الحشرات'}) في مدينة (${city || 'المملكة العربية السعودية'}): نوصي دائماً باستخدام مبيدات معتمدة من هيئة الغذاء والدواء SFDA عديمة الرائحة وآمنة على الأطفال. يتوفر لدينا فريق فني معتمد يمكنه زيارتك ومعاينة المكان خلال 30 دقيقة مع ضمان كتابي معتمد. يمكنك الضغط على زر الحجز السريع أو التواصل عبر الواتساب فوراً.`,
        suggestedActions: [
          'طلب فحص ومعاينة فورية مجانية',
          'حساب التكلفة الدقيقة عبر الحاسبة',
          'التواصل المباشر مع مشرف الفرع'
        ]
      });
    }

    const ai = new GoogleGenAI({ apiKey });

    const systemInstruction = `
أنت "المهندس الاستشاري الفني" لدى مؤسسة "حصن المملكة لمكافحة الحشرات والوقاية الإنشائية والتعقيم" المعتمدة في المملكة العربية السعودية.
مهمتك تقديم استشارات علمية، دقيقة، موثوقة، ومطمئنة للعملاء في كافة مدن ومحافظات السعودية.

معلومات المؤسسة:
- الاسم: مؤسسة حصن المملكة لمكافحة الحشرات والتعقيم
- التخصص: خدمات مكافحة الحشرات، رش المبيدات الآمنة، حقن النمل الأبيض، وطرد الحمام.
- التغطية: تشمل كافة مدن السعودية (الرياض، جدة، مكة، المدينة، الدمام والخبر، الأحساء، الطائف، تبوك، أبها وخميس مشيط، القصيم، حائل، جازان، نجران، الخرج، ينبع وغيرها).
- المميزات: مبيدات ألمانية وأمريكية وسويسرية أصلية بدون رائحة وبدون مغادرة، ضمانات تصل إلى 15 سنة للنمل الأبيض وسنة للصراصير وبق الفراش، وصول الفني خلال 25-35 دقيقة.
- الاتصال الموحد وواتساب: 0558141870

إرشادات الإجابة:
1. التحدث بلغة عربية سعودية مهنية وودودة ومطمئنة.
2. تشخيص المشكلة بدقة وشرح أسباب ظهور الحشرة وطرق التخلص منها بدون مخاطر على الأطفال أو كبار السن أو الحيوانات الأليفة.
3. التوصية بالحل الأنسب (مثلاً: الجل الألماني للصراصير، البخار 180°C للبق، الحقن العازل ومبيد بايفلكس للنمل الأبيض، الطعوم الجافة للقوارض).
4. اختتام الرد بدعوة لطيفة للتواصل عبر الهاتف أو الواتساب لحجز موعد طارئ وفحص مجاني.
5. حافظ على إيجاز الرد ووضوحه (في نقاط منظمة).
`;

    const userPrompt = `
المدينة: ${city || 'غير محددة'}
نوع الحشرة أو المشكلة: ${pestIssue || 'استشارة عامة'}
سؤال العميل: ${message}
`;

    const response = await ai.models.generateContent({
      model: 'gemini-2.5-flash',
      contents: [
        {
          role: 'user',
          parts: [{ text: userPrompt }]
        }
      ],
      config: {
        systemInstruction: {
          parts: [{ text: systemInstruction }]
        },
        temperature: 0.7
      }
    });

    const replyText = response.text || 'يسعدنا خدمتك عبر التواصل المباشر مع فريقنا الفني على الرقم 0558141870.';

    return NextResponse.json({
      reply: replyText,
      suggestedActions: [
        'حجز موعد فحص فوري خلال 30 دقيقة',
        'معرفة السعر عبر حاسبة التكلفة',
        'التحدث مع الفني عبر واتساب'
      ]
    });
  } catch (error) {
    console.error('Gemini Consultation API Error:', error);
    return NextResponse.json({
      reply: 'شكراً لتواصلك مع حصن المملكة. فريقنا الفني متواجد على مدار 24 ساعة لخدمتك في جميع مدن المملكة. يمكنك الاتصال بنا مباشرة على 0558141870 أو مراسلتنا عبر الواتساب للحصول على استشارة فورية وحجز الموعد.',
      suggestedActions: ['اتصال هاتفي مباشر', 'محادثة واتساب سريعة']
    });
  }
}
